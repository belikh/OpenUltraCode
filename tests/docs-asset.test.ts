import { shippedFusionDefaults } from "./fixtures/models.js"

// The README must document the fusion defaults the repository actually ships (read from the
// agent files, so the test never names a provider itself).
itShipped("README documents the shipped fusion defaults", () => {
  const readme = readShippedFile(joinPath(process.cwd(), "README.md"), "utf8")
  for (const reference of new Set(Object.values(shippedFusionDefaults()))) {
    assert.ok(readme.includes(reference), `README.md does not mention the shipped default ${reference}`)
  }
})

type DocExpectation = Readonly<{
  file: string
  required: readonly RegExp[]
}>

const docs: readonly DocExpectation[] = [
  {
    file: "README.md",
    required: [
      /install/i,
      /opencode/i,
      /restart/i,
      /pnpm/i,
      /install\.sh/i,
      /install-dev\.sh/i,
      /latest release/i,
      /GitHub release asset/i,
      /OpenCode 2/i,
      /plugins.*package|package.*plugins/is,
      /\/ultracode-fusion-models/i,
      /opencode models/i,
      /multi-column/i,
      /### Removal/,
      /-remove/,
      /-Remove/,
      /install\.ps1.*-Remove|\.\\install\.ps1 -Remove/is,
      /^1\. Install the latest release with `curl -fsSL https:\/\/raw\.githubusercontent\.com\/belikh\/OpenUltraCode\/main\/install\.sh \| sh`\./im,
      /~\/\.config\/opencode/i,
      /global plugin, commands, skills, and agents/i,
      /minimumReleaseAge: 4320/i,
      /selected model/i,
      /no proxy/i,
      /does not replace/i,
      /skill is named `open-ultracode`/i,
      /not a slash command/i,
      /\/ultracode\s+"/i,
      /\/ultracode-debug\s+"/i,
      /\/ultracode-spec-audit\s+"/i,
      /\/ultracode-research\s+"/i,
      /\/ultrathink\s+"/i,
      /\/ultrathink-fusion/i,
      /grounded/i,
      /loose recall/i
    ]
  }
] as const

function readDoc(file: string): string {
  return readFileSync(join(process.cwd(), file), "utf8")
}

describe("OpenUltraCode documentation assets", () => {
  for (const doc of docs) {
    it(`${doc.file} explains required user-facing behavior`, () => {
      const content = readDoc(doc.file)

      assert.match(content, /^#\s+\S+/m)
      assert.doesNotMatch(content, /guarantees hidden reasoning/i)
      assert.doesNotMatch(content, /bypass provider limits/i)
      assert.doesNotMatch(content, /routes requests through a proxy/i)

      for (const requiredText of doc.required) {
        assert.match(content, requiredText)
      }
    })
  }
})

// The pages in docs/ are generated from docs-src/ with jupiter-docs (github.com/belikh/docs).
// `pnpm run docs:check` and the Docs workflow run the generator; it needs a download, so these
// tests stay offline. They check what can go wrong without it: a page that was never generated,
// a page edited by hand, and a reference page that no longer lists what the code ships.
describe("OpenUltraCode documentation pages", () => {
  const markdownBelow = (directory: string, prefix = ""): string[] =>
    readdirSync(join(process.cwd(), directory, prefix), { withFileTypes: true }).flatMap((entry) => {
      const relative = prefix === "" ? entry.name : `${prefix}/${entry.name}`
      if (entry.isDirectory()) return markdownBelow(directory, relative)
      return entry.name.endsWith(".md") ? [relative] : []
    })
  const sources = markdownBelow("docs-src")
  const generatedPath = (source: string) => (source === "index.md" ? "README.md" : source)

  it("has a generated page in docs/ for every page in docs-src/", () => {
    assert.ok(sources.length > 0)
    for (const source of sources) {
      const generated = join(process.cwd(), "docs", generatedPath(source))
      assert.ok(existsSync(generated), `docs/${generatedPath(source)} is missing; run jupiter-docs build --md`)
      assert.ok(
        readFileSync(generated, "utf8").startsWith(`<!-- Generated by jupiter-docs from docs-src/${source}.`),
        `docs/${generatedPath(source)} was not generated from docs-src/${source}`
      )
    }
  })

  it("holds no hand-written or orphaned page in docs/", () => {
    const expected = new Set(sources.map(generatedPath))
    for (const page of markdownBelow("docs")) {
      assert.ok(expected.has(page), `docs/${page} has no source in docs-src/; delete it or add the source`)
    }
  })

  it("lists every tool, command and agent the repository ships in the reference pages", () => {
    const page = (name: string) => readDoc(`docs-src/reference/${name}.md`)
    const quotedToolNames = /"(open_ultracode_[a-z_]+)"/gu
    const tools = new Set(
      ["src/tools.ts", "src/fusion-tools.ts"].flatMap((file) => [...readDoc(file).matchAll(quotedToolNames)].map((match) => match[1] ?? ""))
    )
    assert.ok(tools.size >= 8, `expected at least 8 tools, found ${[...tools].join(", ")}`)
    for (const tool of tools) assert.match(page("tools"), new RegExp(`^## ${tool}$`, "mu"), `reference/tools.md has no section for ${tool}`)

    const shipped = (directory: string) => readdirSync(join(process.cwd(), directory)).filter((name) => name.endsWith(".md")).map((name) => name.replace(/\.md$/u, ""))
    for (const command of shipped(".opencode/commands")) assert.ok(page("commands").includes(`\`/${command}`), `reference/commands.md does not list /${command}`)
    for (const agent of shipped("assets/agents")) assert.ok(page("agents").includes(`\`${agent}\``), `reference/agents.md does not list ${agent}`)
  })
})
